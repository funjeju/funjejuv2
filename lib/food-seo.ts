/**
 * 도민맛집 SEO 데이터 — 룰 기반 생성.
 *
 * 589개 전체를 빌드타임에 비용 0으로 채운다.
 * - 3-레이어 키워드: 헤비(제주맛집/제주여행) × 지역(애월·성산) × 롱테일(가게×지역×메뉴×의도)
 * - intro: 메뉴 유형별 3문단 구조 SEO 본문 (~500자, 구글/네이버 최소 분량 충족)
 *   1문단: 가게·지역·메뉴 핵심 소개 (헤비 키워드)
 *   2문단: 메뉴 특징 + 제주 식재료·식문화 맥락 (문맥 키워드)
 *   3문단: 방문 팁 + 제주 여행 동선 연계 (롱테일 키워드)
 * - faqs: 위치/영업시간/가격/도민인증 → FAQPage JSON-LD 매핑
 *
 * AI 보강(하이브리드): 상위 트래픽 맛집은 `getFoodSeoOverride(id)`(Firestore)로
 * 고유 설명을 캐싱해 룰 결과를 override한다.
 */

import type { Restaurant } from "@/types/restaurant";
import { parseOptions, formatHours } from "@/lib/restaurants";

export type FoodSeoData = {
  keywords: string[];
  longTailKeywords: string[];
  intro: string;          // SEO 본문 (3문단, \n\n 구분)
  faqs: { q: string; a: string }[];
  highlights: string[];   // 방문 포인트 칩
};

/** 메뉴 텍스트(자유 입력) → 유형별 SEO 본문 3문단 (~500자) */
function menuTemplate(menu: string, region: string, title: string): { intro: string; highlights: string[] } {
  const has = (...ks: string[]) => ks.some((k) => menu.includes(k));

  if (has("흑돼지", "근고기", "고기", "돼지", "오겹", "구이"))
    return {
      intro: `${title}은(는) 제주 ${region}에 자리한 흑돼지 구이 전문 맛집입니다. 제주 청정 자연에서 자란 흑돼지 특유의 쫄깃한 식감과 진한 풍미를 즐길 수 있어, 제주 여행 중 고기 한 점이 생각날 때 가장 먼저 떠오르는 ${region} 대표 고기 맛집입니다.

제주 흑돼지는 육지 돼지와 달리 재래종으로 제주 특유의 청정 환경 속에서 자라 지방이 고르게 분포하고 육질이 부드러운 것이 특징입니다. 껍데기째 불에 구워 먹는 제주식 오겹살은 육지에서는 맛보기 어려운 제주만의 식문화로, 제주 여행을 완성하는 필수 먹거리로 손꼽힙니다. 두툼하게 썬 고기를 직화로 구워 참기름·소금에 찍어 먹는 제주식 먹는 법도 빠뜨릴 수 없는 경험입니다.

제주 여행 중 ${region} 일대를 둘러보다 출출해질 때, 또는 오름·해변 코스 후 한 끼를 제대로 챙기고 싶을 때 방문해 보세요. 현지인도 즐겨 찾는 검증된 ${region} 흑돼지 맛집으로, 주말 저녁에는 웨이팅이 생길 수 있으니 여유 있게 방문하는 것을 권장합니다.`,
      highlights: ["제주 흑돼지 전문", `${region} 고기 맛집`, "제주 여행 필수 먹거리"],
    };

  if (has("회", "물회", "해산물", "갈치", "고등어", "전복", "해물", "조개", "문어", "오징어", "성게", "해녀"))
    return {
      intro: `${title}은(는) 제주 ${region}의 해산물 전문 맛집입니다. 제주 앞바다에서 갓 잡아 올린 싱싱한 해산물로 차려낸 음식을 맛볼 수 있어, 제주 바다의 깊은 맛을 제대로 느끼고 싶은 여행객들에게 꾸준히 인기를 끌고 있는 ${region} 대표 해산물 맛집입니다.

제주 해산물은 청정 제주 바다에서 자란 덕분에 신선도와 맛이 뛰어납니다. 제주 갈치·고등어·전복 등은 제주 여행의 대표 먹거리로, ${region} 인근 바다에서 직접 잡아 올린 재료를 사용하는 현지 맛집에서 더욱 생생한 제주 바다의 맛을 경험할 수 있습니다. 특히 해녀가 직접 채취한 신선한 전복·성게·문어는 제주에서만 맛볼 수 있는 진미로 손꼽힙니다.

제주 여행 중 ${region} 해안 드라이브나 바다 산책 후 신선한 해산물 한 상을 즐기기에 최적인 곳입니다. 제주 현지인도 즐겨 찾는 ${region} 해산물 맛집으로, 제주 여행 식사 코스에 꼭 포함해 볼 것을 추천합니다.`,
      highlights: ["제주 신선 해산물", `${region} 회·해산물`, "제주 바다 먹거리"],
    };

  if (has("카페", "커피", "디저트", "베이커리", "브런치", "빵", "차", "티"))
    return {
      intro: `${title}은(는) 제주 ${region}에 자리한 감성 카페입니다. 제주 특유의 자연 경관과 여유로운 분위기 속에서 커피 한 잔의 시간을 보낼 수 있어, 제주 여행 중 ${region} 일대를 둘러보다 쉬어가기 좋은 공간으로 주목받고 있습니다.

${region}은 아름다운 해안선과 오름, 감귤밭 등 제주 특유의 풍경이 어우러진 지역입니다. ${title}은(는) 이런 제주 ${region}의 분위기를 고스란히 담아낸 공간으로, 감성적인 인테리어와 제주 특산물을 활용한 메뉴들로 제주 여행의 특별한 기억을 선물합니다. 제주 한라봉·녹차·흑임자 등 제주 식재료를 담은 디저트와 음료는 이곳에서만 맛볼 수 있는 특별한 경험입니다.

제주 여행 중 ${region} 드라이브 코스나 오름·해변 방문 후 잠깐 들러 여유를 즐기기에 더없이 좋습니다. 제주 감성 카페를 찾는 여행객에게 추천하는 ${region} 카페로, 편안한 제주 여행의 쉼터가 되어 줄 것입니다.`,
      highlights: ["제주 감성 카페", `${region} 카페`, "제주 여행 쉼터"],
    };

  if (has("국수", "고기국수", "국밥", "칼국수", "면", "탕", "국"))
    return {
      intro: `${title}은(는) 제주 ${region}의 국수·국물 요리 전문 맛집입니다. 제주식 진한 국물과 넉넉한 고명을 얹은 한 그릇으로, 현지인도 즐겨 찾는 ${region} 향토 맛집으로 자리 잡고 있습니다.

제주 고기국수는 제주 특유의 돼지 육수로 우려낸 진하고 구수한 국물에 면을 넣어 먹는 향토 음식으로, 제주 여행 중 현지 식문화를 경험하고 싶다면 꼭 한 번 맛봐야 할 메뉴입니다. 조미료 없이 푹 고아낸 제주식 육수와 쫄깃한 면발의 조화가 이 맛집의 가장 큰 특징으로, 추운 날씨에도 더운 날씨에도 한 그릇 뚝딱하게 만드는 묘한 중독성이 있습니다.

이른 아침이나 늦은 점심, 제주 관광 후 출출한 배를 든든하게 채우기 좋은 ${region} 맛집입니다. 현지인들이 꾸준히 찾는 ${region} 국수 맛집으로, 제주 향토 음식의 진수를 경험하고 싶은 여행객에게 강력히 추천합니다.`,
      highlights: ["제주 향토 국수", `${region} 국물요리`, "현지인 맛집"],
    };

  if (has("갈비", "한우", "소고기", "등심", "육회"))
    return {
      intro: `${title}은(는) 제주 ${region}에 자리한 소고기·갈비 전문 맛집입니다. 엄선된 고기를 제주 특유의 방식으로 조리해 선보이는 곳으로, 제주 여행 중 특별한 한 끼를 원하는 분들이 즐겨 찾는 ${region} 맛집입니다.

제주는 청정 자연 환경 덕분에 질 좋은 소고기 산지로도 알려져 있습니다. ${title}은(는) 신선한 재료를 바탕으로 한 정갈한 상차림과 정성스러운 조리로, 고기 본연의 맛을 최대한 살린 음식을 선보입니다. 갈비찜·육회·구이 등 다양한 소고기 요리를 한자리에서 즐길 수 있는 것도 이 맛집의 장점입니다.

제주 여행 중 ${region}에서 특별한 식사 자리를 찾고 있다면 ${title}을(를) 방문해 보세요. 가족 모임이나 특별한 날의 식사 장소로도 손색없는 ${region} 고기 맛집으로, 제주 여행의 소중한 한 끼를 더욱 특별하게 만들어 줄 것입니다.`,
      highlights: ["소고기·갈비 전문", `${region} 고기 맛집`, "제주 여행 특별 식사"],
    };

  return {
    intro: `${title}은(는) 제주 ${region}에 자리한 ${menu} 전문 맛집입니다. 제주 현지의 신선한 재료와 정성 어린 손맛을 살린 음식으로, 제주 여행 중 ${region}을 방문하는 이들에게 꾸준히 사랑받는 현지 맛집입니다.

${region}은 제주도의 다양한 자연 경관과 가까이 위치해 제주 여행의 주요 코스로 자주 오르내리는 지역입니다. ${title}은(는) 이런 ${region}의 매력 있는 입지 속에서 제주 특유의 식재료를 활용한 ${menu}을(를) 선보이며, 제주 여행의 식탁을 더욱 풍성하게 해 주는 맛집입니다. 제주 현지에서 나고 자란 재료를 사용해 만들어 내는 음식은 어디서도 쉽게 경험하기 어려운 제주만의 맛입니다.

제주 여행 중 ${region} 일대를 둘러보다 식사 자리를 찾고 있다면 ${title}을(를) 방문해 보세요. 현지인도 즐겨 찾는 검증된 ${region} 맛집으로, 제주 여행의 소중한 한 끼를 책임질 것입니다.`,
    highlights: [`제주 ${menu}`, `${region} 맛집`, "제주 여행 먹거리"],
  };
}

export function ruleFoodSeo(r: Restaurant): FoodSeoData {
  const { title, region, menu } = r;
  const options = parseOptions(r.options);
  const hours = formatHours(r.hours);
  const certified = options.includes("펀제주인증");

  // 헤비 × 지역 키워드
  const core = [
    title,
    `${title} 맛집`,
    `${title} 제주`,
    `${region} ${menu}`,
    `${region} ${menu} 맛집`,
    `${region} 맛집`,
    `제주 ${menu}`,
    `제주 ${menu} 맛집`,
    `제주 맛집`,
    `제주도 맛집`,
    `제주도 ${menu}`,
  ];

  // 롱테일 (가게 × 지역 × 메뉴 × 검색의도)
  const longTail = [
    `${region} ${menu} 추천`,
    `${region} 맛집 추천`,
    `제주 ${menu} 맛집 추천`,
    `${title} 가격`,
    `${title} 영업시간`,
    `${title} 메뉴`,
    `${title} 예약`,
    `${region} 가볼만한 맛집`,
    `제주 여행 ${menu}`,
    `${region} 현지인 맛집`,
    `제주 ${region} 맛집`,
    `${menu} 잘하는 집 ${region}`,
    `제주 ${region} 여행 맛집`,
    `${region} 맛집 추천 현지인`,
    certified && `제주 도민 맛집 ${region}`,
    certified && `${region} 현지인 추천 맛집`,
    certified && `펀제주 인증 맛집`,
  ].filter(Boolean) as string[];

  const tmpl = menuTemplate(menu, region, title);

  const faqs = [
    {
      q: `${title}은(는) 어디에 있나요?`,
      a: `${title}은(는) 제주특별자치도 ${region}${r.address ? ` (${r.address})` : ""}에 위치한 ${menu} 맛집입니다. 제주 ${region} 일대를 여행하실 때 방문하기 좋은 위치에 있습니다.`,
    },
    hours
      ? {
          q: `${title} 영업시간은 어떻게 되나요?`,
          a: `${title}의 영업시간은 ${hours}입니다. 성수기·공휴일에는 영업시간이 변경될 수 있으니 방문 전 확인하시는 것을 권장합니다.`,
        }
      : {
          q: `${title} 영업시간은 어떻게 되나요?`,
          a: `영업시간은 변동이 있을 수 있으니 방문 전에 전화 또는 SNS를 통해 미리 확인하시는 것을 권장합니다.`,
        },
    r.prices
      ? { q: `${title} 가격대는 어느 정도인가요?`, a: `${r.prices} 제주 여행 예산 계획 시 참고하세요.` }
      : { q: `${title} 가격대는 어느 정도인가요?`, a: `가격 정보는 변동될 수 있으니 방문 전 확인하시는 것을 권장합니다. 제주 현지 ${menu} 맛집 평균 가격대를 참고하시면 됩니다.` },
    {
      q: `${region}에서 ${menu} 맛집을 찾는다면?`,
      a: `${title}을(를) 추천합니다. 제주 ${region} 여행 중 들르기 좋은 ${menu} 맛집으로, 현지인도 즐겨 찾는 검증된 곳입니다. 제주 여행 동선과 함께 계획해 보세요.`,
    },
    {
      q: `${title}에 주차가 가능한가요?`,
      a: `주차 가능 여부는 방문 전 미리 확인하시는 것을 권장합니다. 제주 ${region} 일대는 주차 공간이 다양하니 인근 공용 주차장도 함께 알아보시면 좋습니다.`,
    },
    certified
      ? {
          q: `${title}은(는) 도민 맛집인가요?`,
          a: `네, ${title}은(는) 펀제주가 인증한 제주 도민 맛집입니다. 제주 현지인이 즐겨 찾는 검증된 곳으로, 관광객보다 현지인 비율이 높은 진짜 제주 맛집입니다.`,
        }
      : null,
  ].filter(Boolean) as { q: string; a: string }[];

  return {
    keywords: [...core, region, menu, "제주맛집", "도민맛집", "제주여행", "펀제주"],
    longTailKeywords: longTail,
    intro: tmpl.intro,
    faqs,
    highlights: tmpl.highlights,
  };
}
